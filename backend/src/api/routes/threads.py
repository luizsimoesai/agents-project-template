from typing import Annotated

from fastapi import APIRouter, Depends, status
from fastapi.responses import StreamingResponse

from src.core.security import get_current_user
from src.schemas.thread import (
    ChatRequest,
    ChatResponse,
    MessageRead,
    ThreadCreate,
    ThreadRead,
)
from src.schemas.user import UserRead
from src.services.assistant_service import AssistantService, get_assistant_service
from src.services.thread_service import ThreadService, get_thread_service

# All thread endpoints require a valid JWT.
# The authenticated user is also injected individually in each handler so we
# can pass str(current_user.id) as user_id to the service layer.
router = APIRouter(
    prefix="/threads",
    tags=["threads"],
    dependencies=[Depends(get_current_user)],
)


@router.post("", status_code=status.HTTP_201_CREATED)
async def create_thread(
    data: ThreadCreate,
    current_user: Annotated[UserRead, Depends(get_current_user)],
    thread_service: Annotated[ThreadService, Depends(get_thread_service)],
) -> ThreadRead:
    """Create a new conversation thread linked to an assistant.

    The thread stores the assistant binding in its metadata so subsequent
    chat messages automatically use the correct graph configuration.
    """
    return await thread_service.create_thread(data, user_id=str(current_user.id))


@router.get("")
async def list_threads(
    current_user: Annotated[UserRead, Depends(get_current_user)],
    thread_service: Annotated[ThreadService, Depends(get_thread_service)],
) -> list[ThreadRead]:
    """Return all conversation threads owned by the authenticated user."""
    return await thread_service.list_threads(user_id=str(current_user.id))


@router.get("/{thread_id}")
async def get_thread(
    thread_id: str,
    current_user: Annotated[UserRead, Depends(get_current_user)],
    thread_service: Annotated[ThreadService, Depends(get_thread_service)],
) -> ThreadRead:
    """Fetch a single thread by ID.

    Returns 404 if the thread does not exist or belongs to another user.
    """
    return await thread_service.get_thread(thread_id, user_id=str(current_user.id))


@router.delete("/{thread_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_thread(
    thread_id: str,
    current_user: Annotated[UserRead, Depends(get_current_user)],
    thread_service: Annotated[ThreadService, Depends(get_thread_service)],
) -> None:
    """Delete a thread and all its message history.

    The LangGraph checkpointer entries (full conversation) are removed via
    Aegra's CASCADE DELETE. Returns 204 on success, 404 if not found.
    """
    await thread_service.delete_thread(thread_id, user_id=str(current_user.id))


@router.post("/{thread_id}/chat")
async def chat(
    thread_id: str,
    body: ChatRequest,
    current_user: Annotated[UserRead, Depends(get_current_user)],
    thread_service: Annotated[ThreadService, Depends(get_thread_service)],
    assistant_service: Annotated[AssistantService, Depends(get_assistant_service)],
) -> ChatResponse:
    """Send a message to the agent and receive its reply (blocking mode).

    The agent uses the assistant's configuration (model, system_prompt, etc.)
    and remembers the full conversation history across calls to this endpoint.

    Flow:
    1. Verify thread ownership and fetch the linked assistant.
    2. Execute the ReAct graph with the user's message.
    3. Return the agent's final reply.

    Note: this endpoint blocks until the agent finishes. For long responses,
    a streaming endpoint (SSE) can be added in a future iteration.
    """
    thread = await thread_service.get_thread(thread_id, user_id=str(current_user.id))
    assistant = await assistant_service.get(
        thread.assistant_id, user_id=str(current_user.id)  # type: ignore[arg-type]
    )
    return await thread_service.chat(thread_id, body.message, assistant)


@router.post("/{thread_id}/chat/stream")
async def stream_chat(
    thread_id: str,
    body: ChatRequest,
    current_user: Annotated[UserRead, Depends(get_current_user)],
    thread_service: Annotated[ThreadService, Depends(get_thread_service)],
    assistant_service: Annotated[AssistantService, Depends(get_assistant_service)],
) -> StreamingResponse:
    """Stream the agent's reply token-by-token using Server-Sent Events (SSE).

    Follows the Aegra/LangGraph streaming format — the same protocol used by
    Aegra's native /threads/{id}/runs/stream endpoint.  Events are emitted in
    this order:
      1. metadata        — run_id for LangSmith/Studio correlation
      2. messages/metadata — message ID and routing metadata (once per message)
      3. messages/partial  — each token as it is generated by the LLM
      4. messages/complete — the full assembled message when streaming finishes
      5. end             — {"status": "success"} on clean completion
      6. error           — emitted instead of 'end' if an exception occurs

    Clients should consume this as a standard SSE stream:
      EventSource  or  fetch() with ReadableStream.

    Returns HTTP 200 with Content-Type: text/event-stream.
    """
    thread = await thread_service.get_thread(thread_id, user_id=str(current_user.id))
    assistant = await assistant_service.get(
        thread.assistant_id, user_id=str(current_user.id)  # type: ignore[arg-type]
    )
    return StreamingResponse(
        thread_service.stream_chat(thread_id, body.message, assistant),
        media_type="text/event-stream",
        headers={
            # Prevent buffering by proxies and the browser's fetch layer.
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
        },
    )


@router.get("/{thread_id}/history")
async def get_history(
    thread_id: str,
    current_user: Annotated[UserRead, Depends(get_current_user)],
    thread_service: Annotated[ThreadService, Depends(get_thread_service)],
) -> list[MessageRead]:
    """Return the full conversation history for a thread.

    History is stored in the LangGraph PostgreSQL checkpointer, not in the
    thread table. Each entry has a role ("human" or "ai") and the message
    content. Returns an empty list if no messages have been sent yet.
    """
    return await thread_service.get_history(thread_id, user_id=str(current_user.id))
